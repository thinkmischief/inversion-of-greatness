#!/usr/bin/env node

// render-markdown-export.js
// Generates a plain-markdown export of the book, meant to be dropped
// straight into an Obsidian vault or imported into Notion (Settings ->
// Import -> Markdown & CSV, which converts matching relative .md links
// between imported files into real internal page links automatically —
// same underlying format serves both, on request, rather than building
// two separate exports).
//
// Splits each chapter at its own numbered headings (## §N.M, ### §N.M.K)
// into one file per section — on request, after the first version (one
// file per whole chapter) missed the actual point of an Obsidian export:
// its value is a dense web of small, atomic, heavily cross-linked notes,
// not long-form chapter documents with buried internal anchors. This
// also sidesteps the anchor-precision problem entirely — every §N.M
// cross-reference now points at a real, separate file, so plain markdown
// links work reliably in both apps; no wikilink/heading-slug-guessing
// needed. Front/back matter and any chapter with no internal numbered
// headings (Copyright, Symbols, Glossary, ...) stays a single file, same
// as before, since there's nothing to split.
//
// Reads the same book/*.qmd files every other format (PDF/EPUB/HTML)
// already derives from — no separate content to maintain. Strips
// everything Quarto/Pandoc-specific that a plain markdown viewer
// wouldn't understand:
//   - Fenced divs (semantic boxes: definition/theorem/premise/etc.,
//     callouts, margin notes) -> blockquotes, since neither target app
//     renders arbitrary div classes.
//   - content-visible when/unless-format="html" -> resolved as if
//     "not html" (same branch PDF/EPUB already use), since this export
//     is a static document like those, not the interactive website.
//   - Raw ```{=latex}``` blocks -> dropped entirely (print-only).
//   - @citekey / [@citekey] citations -> resolved to "(Author, Year)" via
//     data/references.json. The bracketed form needs the brackets
//     stripped along with the @-token, not just the token replaced in
//     place — leaving them produced "[(Author, Year)]", which Obsidian
//     renders as a dangling, non-functional link (reported live).
//   - [text](chapter.html#sec-N-M) cross-references -> [text](section.md)
//     — resolved to the exact split-out section file.
//   - {#sec-N-M} heading-id attributes -> stripped from the heading text.
//
// Output: markdown-export/{files}, plus a zip of the same for the site's
// download link.

const fs = require('fs')
const path = require('path')
const { execSync } = require('child_process')

const ROOT   = __dirname
const BOOK   = path.join(ROOT, 'book')
const OUTDIR = path.join(ROOT, 'markdown-export')

// Reading order, matching _quarto.yml's own chapters: list exactly.
// bibliography isn't in chapters: at all (linked only from the navbar,
// generated by a separate script) but is a real file here — placed in
// its normal back-matter position since there's no _quarto.yml entry to
// derive that from.
const READING_ORDER = [
  'front-copyright', 'front-preface', 'front-introduction',
  'groundwork', 'the-argument', 'convergence', 'metaphysical-rivals',
  'rival-ultimates', 'relocating-greatness', 'nature-alone',
  'expanding-the-field', 'maximum-possibility', 'conclusion', 'excursus',
  'modal-logic-primer', 'formal-proof-summary', 'derivation-map',
  'empirical-predictions', 'authors-notes',
  'symbols', 'glossary', 'notes', 'bibliography', 'subject-index',
]

// Obsidian's own native callout syntax (> [!type]) — a real colored,
// icon-decorated, collapsible box, distinct per type — on request, in
// place of a plain blockquote where every box looked identical regardless
// of whether it was a definition, theorem, or premise. Mapped to
// Obsidian's actual built-in types where one is a genuine semantic match
// (note/info/quote — real default styling); the book's own
// domain-specific types (definition, theorem, ...) use custom callout
// names, which Obsidian still renders as valid, functional, collapsible
// boxes — just with generic default coloring unless a matching CSS
// snippet is added to the vault later. Not standard markdown, so
// Notion's importer won't render these specially (shows the literal
// "[!type]" tag as text) — same tradeoff already accepted for the
// wikilink-based section jumps, on the same "optimize for where this
// actually shines" call.
const CALLOUT_TYPES = {
  definition: 'definition',
  theorem: 'theorem',
  lemma: 'lemma',
  corollary: 'corollary',
  premise: 'premise',
  principle: 'principle',
  argument: 'argument',
  identification: 'identification',
  'callout-note': 'note',   // real Obsidian built-in
  'column-margin': 'info',  // closest built-in for a marginal/supplementary note
  'standout-line': 'quote', // real Obsidian built-in, fits a pull-quote
  untyped: null,             // no clear type — stays a plain blockquote, no callout wrapper
}

// citekey -> "Authors, Year" for resolving @citekey inline citations
const references = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'references.json'), 'utf8'))
const citeMap = {}
for (const r of references) {
  if (r.Citekey) citeMap[r.Citekey] = `${r.Authors}, ${r.Year}`
}

// Bracketed form first ([@key] / [@key1; @key2, III] / [-@key]) — must run
// before the bare-@ pass below, and must consume the surrounding brackets
// themselves, not just the @token inside them (confirmed live: leaving
// "[(Author, Year)]" behind renders as a dangling link in Obsidian).
// Falls back to leaving a bracketed cite unresolved (rather than partially
// mangling it) if any key inside it isn't in references.json.
function resolveCitations(text) {
  // Pandoc's [@key suffix text; @key2 ...] citation-group syntax allows
  // arbitrary free-text locators/suffixes after each key (e.g. "@key on
  // topology in formal language") — too open-ended to fully parse
  // reliably. Since a [...] bracket containing an @ is always Pandoc
  // citation syntax in this book (never coincidental literal brackets
  // around unrelated prose), just strip the outer pair and let the
  // bare-@ pass below resolve each key in place — correct, readable
  // prose either way, without needing the full suffix grammar.
  // Allows one level of nested [...] inside (e.g. a citation group that
  // also contains an inline cross-reference link, [@key; [§6.2.2](file.md)
  // develops...]) — a plain negated-bracket class can't match across that.
  let out = text.replace(/\[((?:[^\[\]]|\[[^\[\]]*\])*@(?:[^\[\]]|\[[^\[\]]*\])*)\]/g, '$1')
  // Bare in-text form: "as @kripke1980 argues" -> "as (Kripke, 1980) argues"
  out = out.replace(/@([a-zA-Z][a-zA-Z0-9]*)/g, (m, key) => (citeMap[key] ? `(${citeMap[key]})` : m))
  return out
}

// Strip {#sec-N-M} (and any other {...} heading attributes) from headings
function stripHeadingAttrs(text) {
  return text.replace(/^(#{1,6}\s+.+?)\s*\{[^}]*\}\s*$/gm, '$1')
}

// Strip raw format-specific blocks: ```{=latex} ... ```
function stripRawBlocks(text) {
  return text.replace(/```\{=\w+\}[\s\S]*?```\n?/g, '')
}

// Turns a block of lines into an Obsidian callout (or a plain blockquote
// for "untyped", which has no real type to tag). No separate label text
// injected here — unlike the old plain-blockquote version, the [!type]
// tag itself is the label, so there's no risk of it duplicating the
// content's own existing "**Term** · *Definition*"-style first line,
// which just stays as the callout's own first line of body text
// unchanged (this is what caused the earlier redundant-label bug, and
// switching to callouts removes the whole class of problem rather than
// needing better detection of it).
function toBlockquote(lines, type) {
  const body = lines.join('\n').trim()
  const header = type ? `[!${type}]` : null
  const quoted = body.split('\n').map(l => (l.trim() ? `> ${l}` : '>')).join('\n')
  return header ? `> ${header}\n${quoted}` : quoted
}

// Stack-based fenced-div parser — Pandoc's ::: fences use a variable-length
// run of colons (3+), and nest by using a LONGER run on the outer fence, so
// a fixed-length regex can't tell an open from a close, or match nesting
// correctly. This walks line by line instead, tracking open fences on a
// stack, exactly the shape needed to unwrap or blockquote-wrap each div by
// the time its matching close is found — including divs nested inside
// content-visible wrappers (confirmed both patterns exist in book/*.qmd).
function processDivs(text) {
  const lines = text.split('\n')
  const stack = [{ children: [] }] // root
  const fenceRe = /^(:{3,})\s*\{([^}]*)\}\s*$/
  const closeRe = /^(:{3,})\s*$/

  for (const line of lines) {
    const openMatch = line.match(fenceRe)
    const closeMatch = !openMatch && line.match(closeRe)

    if (openMatch) {
      const [, colons, attrs] = openMatch
      const classMatch = attrs.match(/\.([\w-]+)/)
      const cls = classMatch ? classMatch[1] : null
      const whenHtml = /when-format="html"/.test(attrs)
      const unlessHtml = /unless-format="html"/.test(attrs)
      stack.push({ colons: colons.length, cls, whenHtml, unlessHtml, children: [] })
    } else if (closeMatch && stack.length > 1 && closeMatch[1].length === stack[stack.length - 1].colons) {
      const frame = stack.pop()
      const inner = frame.children.join('\n')
      let rendered
      if (frame.whenHtml) {
        rendered = '' // dropped — this export isn't the html/website format
      } else if (frame.unlessHtml) {
        rendered = inner // unwrapped — same branch PDF/EPUB already use
      } else if (frame.cls && Object.prototype.hasOwnProperty.call(CALLOUT_TYPES, frame.cls)) {
        rendered = toBlockquote(frame.children, CALLOUT_TYPES[frame.cls])
      } else {
        rendered = inner // unknown/unhandled class — pass through rather than lose content
      }
      stack[stack.length - 1].children.push(rendered)
    } else {
      stack[stack.length - 1].children.push(line)
    }
  }
  while (stack.length > 1) {
    const frame = stack.pop()
    stack[stack.length - 1].children.push(frame.children.join('\n'))
  }
  return stack[0].children.join('\n')
}

// Half-open interval notation ("[t0, infinity)") uses a literal [ closed
// by a ) instead of a matching ] — syntactically a dangling, unclosed [
// to a markdown parser, which then keeps scanning forward for the next ]
// it can find. Reported live: when a real [text](file.md) link appeared
// later in the same paragraph, everything in between got swallowed into
// one giant link. Escaping just the [ in this specific shape (immediately
// followed by non-bracket content and a closing ), never followed by a
// real closing ]) sidesteps it without touching genuine links, footnote
// refs ([^id]), or citation brackets ([@key]) — none of those match this
// pattern, since a real ] always appears before any ) in each of them.
function escapeIntervalBrackets(text) {
  return text.replace(/\[(?=[^[\]]*\))/g, '\\[')
}

function convert(text) {
  let out = text
  out = stripRawBlocks(out)
  out = escapeIntervalBrackets(out)
  out = processDivs(out)
  out = stripHeadingAttrs(out)
  out = resolveCitations(out)
  out = out.replace(/\n{3,}/g, '\n\n') // collapse blank-line runs left by dropped/unwrapped blocks
  return out.trim() + '\n'
}

function getTitle(text) {
  const fm = text.match(/^---\n([\s\S]*?)\n---/)
  if (!fm) return null
  const m = fm[1].match(/^title:\s*"([^"]*)"/m)
  return m ? m[1] : null
}

// A sequential position number alone would tell a reader nothing about
// which of the book's own 9 numbered chapters (or 4 lettered appendices)
// they're looking at. Parsed from each file's own title (e.g. "3.
// Convergence", "Appendix B: Formal Proof Summary") rather than a second,
// separately-maintained table, so it can't drift out of sync.
function extractChapterLabel(title) {
  if (!title) return null
  const chapter = title.match(/^(\d+)\.\s/)
  if (chapter) return `ch${chapter[1]}`
  const appendix = title.match(/^Appendix\s+([A-Z]):/)
  if (appendix) return `appendix-${appendix[1].toLowerCase()}`
  return null
}

// Splits a chapter body at its own numbered headings (## N.M, ### N.M.K —
// the same pattern add-section-anchors.js used to add {#sec-N-M} in the
// first place, so this only ever splits at points that genuinely have an
// anchor and so a genuine cross-reference target elsewhere in the book).
// Content before the first such heading (chapter-level intro prose)
// becomes the chapter-index section (num: null).
function splitIntoSections(body) {
  const lines = body.split('\n')
  const HEADING_RE = /^(#{2,4})\s+(\d+(?:\.\d+){0,2})\s+(.+?)\s*\{[^}]*#(sec-[0-9-]+)[^}]*\}\s*$/
  const sections = []
  let current = { num: null, title: null, id: null, level: 0, lines: [] }

  for (const line of lines) {
    const m = line.match(HEADING_RE)
    if (m) {
      sections.push(current)
      const [, hashes, num, title, id] = m
      current = { num, title, id, level: hashes.length, lines: [] }
    } else {
      current.lines.push(line)
    }
  }
  sections.push(current)
  return sections
}

// Obsidian (and most markdown file browsers) display the FILENAME itself
// as the note's title automatically — an embedded "# Title" heading
// inside the content on top of that renders as two stacked titles
// (reported live, screenshot showed exactly this: "03-01-02-the-
// unswitchable-capacity" as the auto-title, then a second "# 3.1.2 The
// Unswitchable Capacity" heading right below it). Fixed by making the
// filename itself the clean, human-readable title — the hyphenated slug
// this replaces was never meant to be visible, just a stable file
// handle — and dropping the redundant embedded heading entirely.
// Windows disallows : < > " / \ | ? * in filenames (only ":" actually
// appears in real titles here, in "Appendix A: Modal Logic Primer" etc.)
function filenamize(text) {
  return text.replace(/[:<>"/\\|?*]/g, '').replace(/\s+/g, ' ').trim()
}

// A clean wipe is preferred (stale files from a since-changed section
// structure shouldn't linger), but Obsidian holds file handles open while
// it has this folder indexed as a vault, which can make a recursive
// delete fail outright rather than just skip the locked file. Falling
// back to overwrite-in-place keeps this runnable while testing changes
// live in an open vault; do a real clean wipe (Obsidian closed) before
// actually shipping this to confirm no orphaned files remain.
try {
  fs.rmSync(OUTDIR, { recursive: true, force: true })
} catch (e) {
  console.warn('Could not fully clear markdown-export/ (likely open in Obsidian) — overwriting in place instead.')
}
fs.mkdirSync(OUTDIR, { recursive: true })

const bookSlugs = fs.readdirSync(BOOK).filter(f => f.endsWith('.qmd')).map(f => f.replace(/\.qmd$/, ''))
const unlisted = bookSlugs.filter(s => !READING_ORDER.includes(s))
if (unlisted.length) {
  console.warn(`WARN: book/*.qmd has file(s) not in READING_ORDER — appending at the end, unnumbered gap: ${unlisted.join(', ')}`)
}
const orderedSlugs = READING_ORDER.filter(s => bookSlugs.includes(s)).concat(unlisted)

// ---- Pass 1: read every chapter, split into sections, assign filenames ----
// Two passes are required — link-rewriting (pass 2) needs every section's
// final filename already resolved, including sections in OTHER chapters.
const chapters = [] // { slug, title, chapterFile, sections: [{...,file}] }
const idToFile = {}  // "sec-1-1-1" -> filename, global across the whole book

orderedSlugs.forEach((slug, i) => {
  const raw = fs.readFileSync(path.join(BOOK, slug + '.qmd'), 'utf8')
  const title = getTitle(raw)
  const body = raw.replace(/^---\n[\s\S]*?\n---\n/, '')
  // A synthetic seq-number prefix ("04 1. Groundwork.md") was tried first
  // for guaranteed folder-sort order (front/back matter like Copyright or
  // Symbols has no natural sort key, and "P. Preface" vs "I. Introduction"
  // don't happen to sort alphabetically in reading order either) — on
  // request, doubling up on numbers like that reads as weird/awkward.
  // Matches the section-file naming fix just above it: the file's own
  // real title, exactly as it appears in the book, nothing added — same
  // tradeoff, guaranteed alphabetical folder-sort given up for a clean
  // title.
  const chapterFile = `${filenamize(title || slug)}.md`

  const sections = splitIntoSections(body)
  const real = sections.filter(s => s.num !== null)

  // Zero-padded segments ("03.01.02") were tried first for guaranteed
  // folder-sort order (some sections run past 9 subsections, so plain
  // "4.1.10" would otherwise sort before "4.1.2") — on request, that
  // reads worse than it's worth. This matches the section number exactly
  // as it appears in the book's own Table of Contents ("3.2.4"), trading
  // guaranteed alphabetical sort order in a flat file browser for that.
  for (const s of real) {
    s.file = `${s.num} ${filenamize(s.title)}.md`
    idToFile[s.id] = s.file
  }

  chapters.push({ slug, title, chapterFile, sections })
})

// ---- Pass 2: convert content and write files ----
// Cross-reference links: [text](chapter.html#sec-N-M) -> [text](section.md)
// if that exact section got split out, else [text](chapterFile) as a
// file-level fallback (e.g. a reference into a chapter that had no
// internal numbered headings to split on).
// CommonMark requires a link destination containing a space to be wrapped
// in <angle brackets> — a bare (8.1 Drive.md) is invalid and cuts off at
// the first space in a strict parser, which is what broke every link
// site-wide the moment filenames switched from hyphenated slugs to
// natural titles with spaces (reported live: clicking a link created a
// new blank page named after the truncated fragment).
function linkDest(file) {
  return file.includes(' ') ? `<${file}>` : file
}

function rewriteLinks(text, chapterFileBySlug) {
  return text.replace(/\]\(([a-z0-9-]+)\.html(?:#(sec-[0-9-]+))?\)/g, (m, slug, secId) => {
    if (secId && idToFile[secId]) return `](${linkDest(idToFile[secId])})`
    const fallback = chapterFileBySlug[slug]
    return `](${linkDest(fallback || slug + '.md')})`
  })
}

const chapterFileBySlug = {}
for (const c of chapters) chapterFileBySlug[c.slug] = c.chapterFile

// The landing-page source (site/markdown-export-intro.qmd — a page
// purpose-written for this export specifically, marked with its own
// "Markdown Export" Surfaces tag so it never renders on the live website)
// links with full site URLs (https://inversionofgreatness.org/modal-
// logic-primer) rather than the book.html#sec-N-M pattern every other
// cross-reference in book/*.qmd uses. Rewrites the ones pointing to real
// book content (an appendix, Author's Notes, ...) into local file links;
// leaves links to website-only pages this export doesn't include as live
// external URLs, since there's nothing local to point them at.
function rewriteSiteLinks(text) {
  return text.replace(/https:\/\/inversionofgreatness\.org\/([a-z0-9-]+)\/?/g, (m, slug) => {
    const target = chapterFileBySlug[slug]
    return target ? linkDest(target) : m
  })
}

// Full front-to-back reading order for the Previous/Next footer — the
// chapter-index file, then its own sections in the same order they
// appear in the source (already depth-first/hierarchical: 1.1, 1.1.1,
// 1.1.2, 1.2, ... since splitIntoSections just walks the file top to
// bottom), then on to the next chapter. On request, as a convenience for
// reading straight through — separate from, not a replacement for, the
// cross-linking that's the actual point of the Obsidian export.
const flatSequence = []
for (const c of chapters) {
  flatSequence.push({ file: c.chapterFile, title: c.title || c.slug })
  for (const s of c.sections.filter(s => s.num !== null)) {
    flatSequence.push({ file: s.file, title: `${s.num} ${s.title}` })
  }
}
function prevNextFooter(file) {
  const i = flatSequence.findIndex(e => e.file === file)
  const prev = i > 0 ? flatSequence[i - 1] : null
  const next = i < flatSequence.length - 1 ? flatSequence[i + 1] : null
  const parts = []
  if (prev) parts.push(`← [${prev.title}](${linkDest(prev.file)})`)
  if (next) parts.push(`[${next.title}](${linkDest(next.file)}) →`)
  return parts.length ? `\n\n---\n\n${parts.join(' | ')}\n` : ''
}

// Landing page: a purpose-written intro (site/markdown-export-intro.qmd —
// explains the format itself, then reuses the book's own five-movements/
// where-to-begin overview) plus a master Table of Contents — every
// chapter in reading order, something this export otherwise lacks
// entirely. Without it, a flat folder just sorts alphabetically once
// filenames dropped their sequence-number prefixes (a separate fix, on
// request), scrambling "1. Groundwork" and "9. Maximum Possibility" in
// among "Appendix A", "Copyright", "Symbols" with no indication of
// reading order at all. This is deliberately NOT the live website's
// actual Home page (tried first, then reconsidered on request — a web
// visitor and someone who already downloaded this export are in
// different situations and need different framing; the website-specific
// bits, like publication-format status and the personal sign-off, don't
// belong here). Placed first in flatSequence so it's also the very first
// stop in the Previous/Next chain.
const LANDING_FILE = 'Start Here.md'
const introRaw = fs.readFileSync(path.join(ROOT, 'site', 'markdown-export-intro.qmd'), 'utf8')
const introBody = introRaw.replace(/^---\n[\s\S]*?\n---\n/, '')
const introConverted = rewriteSiteLinks(convert(introBody))
const masterToc = chapters.map(c => `- [${c.title || c.slug}](${linkDest(c.chapterFile)})`).join('\n')
const landingBody = `${introConverted}\n\n## Table of Contents\n\n${masterToc}\n`
flatSequence.unshift({ file: LANDING_FILE, title: 'Start Here' })

let count = 0
fs.writeFileSync(path.join(OUTDIR, LANDING_FILE), landingBody + prevNextFooter(LANDING_FILE), 'utf8')
count++
for (const c of chapters) {
  const real = c.sections.filter(s => s.num !== null)
  const intro = c.sections.find(s => s.num === null)

  // Chapter-index file: just the chapter's own intro prose, nothing else.
  // Used to also append a linked list of its own top-level (##) sections
  // here — removed on request: the root/chapter file shouldn't carry a
  // pile of sub-pages listed inside it. Reaching those sections is what
  // the master Table of Contents (Start Here.md) and the Previous/Next
  // chain are already for.
  const indexBody = rewriteLinks(convert(intro.lines.join('\n')), chapterFileBySlug)
  // No embedded "# Title" heading — the filename itself (e.g. "04 1.
  // Groundwork.md") is what Obsidian/Notion display as the title
  // automatically; adding one here would just stack a second title
  // directly below the first (confirmed live via screenshot).
  fs.writeFileSync(path.join(OUTDIR, c.chapterFile), indexBody + prevNextFooter(c.chapterFile), 'utf8')
  count++

  for (const s of real) {
    let sectionBody = rewriteLinks(convert(s.lines.join('\n')), chapterFileBySlug)
    // Subsections of this section get their own linked list too (mirrors
    // the chapter-index treatment one level down).
    const children = real.filter(child => child.num !== s.num && child.num.startsWith(s.num + '.') && child.level === s.level + 1)
    if (children.length) {
      const toc = children.map(ch => `- [${ch.num} ${ch.title}](${linkDest(ch.file)})`).join('\n')
      sectionBody = sectionBody.trim() ? `${sectionBody}\n\n${toc}\n` : `${toc}\n`
    }
    fs.writeFileSync(path.join(OUTDIR, s.file), sectionBody + prevNextFooter(s.file), 'utf8')
    count++
  }
}

console.log(`Wrote ${count} markdown file(s) to ${path.relative(ROOT, OUTDIR)}/`)

// Stable, version-free download path (author decision, 2026-07-31) — same
// convention as render-pdf.js/render-epub.js's own downloads/ output.
// downloads/ is a real, git-tracked folder (unlike markdown-export/,
// gitignored), overwritten each time this script runs.
const downloadsDir = path.join(ROOT, 'downloads')
fs.mkdirSync(downloadsDir, { recursive: true })
const zipPath = path.join(downloadsDir, 'the-inversion-of-greatness-markdown.zip')
fs.rmSync(zipPath, { force: true })
try {
  // PowerShell's Compress-Archive, not the `zip` CLI — this repo's own
  // dev environment is Windows/Git Bash, where `zip` isn't installed by
  // default but powershell.exe always is. Netlify's own Linux build
  // environment does have `zip`, so this falls back to it there.
  if (process.platform === 'win32') {
    execSync(
      `powershell -NoProfile -Command "Compress-Archive -Path '${OUTDIR}\\*' -DestinationPath '${zipPath}' -Force"`,
    )
  } else {
    execSync(`cd "${OUTDIR}" && zip -r -q "${zipPath}" .`, { shell: '/bin/bash' })
  }
  console.log(`Zipped to ${path.relative(ROOT, zipPath)}`)
} catch (e) {
  console.warn('Zipping failed — markdown-export/ folder is still available unzipped.')
  console.warn(e.message)
}
